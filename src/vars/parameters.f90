module parameters

    implicit none
    save

    integer, allocatable :: catchments_per_subbasin(:)
    character(10), allocatable :: hru_name(:)
    integer, allocatable :: subbasin_outlet_catchment(:)
    real, allocatable :: river_width(:)
    integer, allocatable :: catchment_subbasin(:), downstream_catchment(:)
    real, allocatable :: longest_reach_slope(:), longest_reach_length(:)
    real, allocatable :: catchment_x(:), catchment_y(:)
    integer, allocatable :: climate_region(:)
    real, allocatable :: catchment_area(:), drainage_area(:), river_length(:), river_slope(:)
    real, allocatable :: hru_percentage(:, :)
    integer, allocatable :: catchment_order(:)
    real, allocatable :: specific_baseflow(:)
    real, allocatable :: max_soil_water_storage(:, :), arno_b(:, :)
    real, allocatable :: subsurface_conductivity(:, :), groundwater_conductivity(:, :)
    real, allocatable :: brooks_corey_lambda(:, :), max_capillary_flux(:, :)
    real, allocatable :: capillary_threshold_fraction(:, :), floodplain_infiltration_rate(:, :)
    real, allocatable :: subsurface_routing_coefficient(:)
    real, allocatable :: groundwater_routing_coefficient(:), surface_routing_coefficient(:)
    real, allocatable :: albedo(:, :, :), leaf_area_index(:, :, :), vegetation_height(:, :, :)
    real, allocatable :: surface_resistance(:, :, :)

    integer, allocatable :: muskingum_reach_count(:)
    real, allocatable :: muskingum_timestep(:)
    real, allocatable :: wave_celerity(:), concentration_time(:), reference_q(:), manning_n(:)

    integer, allocatable :: upstream_topology(:, :)
    integer, allocatable :: floodplain_point_count(:), floodplain_bottom_elevation(:)
    integer, allocatable :: floodplain_elevation(:, :)
    real*8, allocatable :: floodplain_area(:, :), bankfull_depth(:)
    real*8, allocatable :: stage_table(:, :), volume_table(:, :), area_table(:, :)
    real*8, allocatable :: inertial_manning_n(:)
    real*8, allocatable :: face_catchment_1(:), face_catchment_2(:)
    real*8, allocatable :: first_face_elevation(:), second_face_elevation(:), face_distance(:)

    integer, allocatable :: reservoir_index_by_catchment(:), routing_downstream_catchment(:)
    integer, allocatable :: reservoir_start_timestep(:)
    integer, allocatable :: substitution_catchment(:)

contains

    subroutine allocate_parameters(requested_catchment_count, requested_subbasin_count, &
        & requested_hru_count, requested_climate_region_count, requested_max_hru_count, &
        & requested_max_subbasin_count, requested_max_muskingum_reach_count)
        integer, intent(in) :: requested_catchment_count, requested_subbasin_count
        integer, intent(in) :: requested_hru_count, requested_climate_region_count
        integer, intent(in) :: requested_max_hru_count, requested_max_subbasin_count
        integer, intent(in) :: requested_max_muskingum_reach_count

        allocate (catchments_per_subbasin(requested_subbasin_count))
        allocate (hru_name(requested_max_hru_count))
        allocate (hru_percentage(requested_catchment_count, requested_hru_count))
        allocate (catchment_area(requested_catchment_count))
        allocate (drainage_area(requested_catchment_count))
        allocate (river_length(requested_catchment_count))
        allocate (river_slope(requested_catchment_count))
        allocate (catchment_x(requested_catchment_count))
        allocate (catchment_y(requested_catchment_count))
        allocate (climate_region(requested_catchment_count))
        allocate (catchment_subbasin(requested_catchment_count))
        allocate (longest_reach_slope(requested_catchment_count))
        allocate (longest_reach_length(requested_catchment_count))
        allocate (downstream_catchment(requested_catchment_count))
        allocate (river_width(requested_catchment_count))
        allocate (subbasin_outlet_catchment(requested_subbasin_count))
        allocate (catchment_order(requested_catchment_count))
        allocate (subsurface_routing_coefficient(requested_subbasin_count))
        allocate (groundwater_routing_coefficient(requested_subbasin_count))
        allocate (surface_routing_coefficient(requested_subbasin_count))
        allocate (brooks_corey_lambda(requested_subbasin_count, requested_hru_count))
        allocate (max_capillary_flux(requested_subbasin_count, requested_hru_count))
        allocate (capillary_threshold_fraction(requested_subbasin_count, requested_hru_count))
        allocate (max_soil_water_storage(requested_subbasin_count, requested_hru_count))
        allocate (arno_b(requested_subbasin_count, requested_hru_count))
        allocate (subsurface_conductivity(requested_subbasin_count, requested_hru_count))
        allocate (groundwater_conductivity(requested_subbasin_count, requested_hru_count))
        allocate (floodplain_infiltration_rate(requested_subbasin_count, requested_hru_count))
        allocate (specific_baseflow(requested_subbasin_count))
        allocate (albedo(requested_hru_count, 12, requested_climate_region_count))
        allocate (leaf_area_index(requested_hru_count, 12, requested_climate_region_count))
        allocate (vegetation_height(requested_hru_count, 12, requested_climate_region_count))
        allocate (surface_resistance(requested_hru_count, 12, requested_climate_region_count))

        allocate (muskingum_reach_count(requested_catchment_count))
        allocate (muskingum_timestep(requested_catchment_count))
        allocate (wave_celerity(requested_catchment_count))
        allocate (concentration_time(requested_catchment_count))
        allocate (reference_q(requested_catchment_count))
        allocate (manning_n(requested_catchment_count))

        allocate (upstream_topology(requested_catchment_count, 10))
        allocate (floodplain_point_count(requested_catchment_count))
        allocate (floodplain_bottom_elevation(requested_catchment_count))
        allocate (floodplain_elevation(100, requested_catchment_count))
        allocate (floodplain_area(100, requested_catchment_count))
        allocate (bankfull_depth(requested_catchment_count))
        allocate (stage_table(102, requested_catchment_count))
        allocate (volume_table(102, requested_catchment_count))
        allocate (area_table(102, requested_catchment_count))
        allocate (inertial_manning_n(requested_catchment_count))
        allocate (face_catchment_1(requested_catchment_count))
        allocate (face_catchment_2(requested_catchment_count))
        allocate (first_face_elevation(requested_catchment_count))
        allocate (second_face_elevation(requested_catchment_count))
        allocate (face_distance(requested_catchment_count))

        allocate (reservoir_index_by_catchment(requested_catchment_count))
        allocate (routing_downstream_catchment(requested_catchment_count))
        allocate (reservoir_start_timestep(requested_catchment_count))
        allocate (substitution_catchment(requested_max_subbasin_count))
    end subroutine allocate_parameters

    subroutine deallocate_parameters
        if (allocated(substitution_catchment)) deallocate (substitution_catchment)
        if (allocated(reservoir_start_timestep)) deallocate (reservoir_start_timestep)
        if (allocated(routing_downstream_catchment)) deallocate (routing_downstream_catchment)
        if (allocated(reservoir_index_by_catchment)) deallocate (reservoir_index_by_catchment)
        if (allocated(face_distance)) deallocate (face_distance)
        if (allocated(second_face_elevation)) deallocate (second_face_elevation)
        if (allocated(first_face_elevation)) deallocate (first_face_elevation)
        if (allocated(face_catchment_2)) deallocate (face_catchment_2)
        if (allocated(face_catchment_1)) deallocate (face_catchment_1)
        if (allocated(inertial_manning_n)) deallocate (inertial_manning_n)
        if (allocated(area_table)) deallocate (area_table)
        if (allocated(volume_table)) deallocate (volume_table)
        if (allocated(stage_table)) deallocate (stage_table)
        if (allocated(bankfull_depth)) deallocate (bankfull_depth)
        if (allocated(floodplain_area)) deallocate (floodplain_area)
        if (allocated(floodplain_elevation)) deallocate (floodplain_elevation)
        if (allocated(floodplain_bottom_elevation)) deallocate (floodplain_bottom_elevation)
        if (allocated(floodplain_point_count)) deallocate (floodplain_point_count)
        if (allocated(upstream_topology)) deallocate (upstream_topology)
        if (allocated(manning_n)) deallocate (manning_n)
        if (allocated(reference_q)) deallocate (reference_q)
        if (allocated(concentration_time)) deallocate (concentration_time)
        if (allocated(wave_celerity)) deallocate (wave_celerity)
        if (allocated(muskingum_timestep)) deallocate (muskingum_timestep)
        if (allocated(muskingum_reach_count)) deallocate (muskingum_reach_count)
        if (allocated(surface_resistance)) deallocate (surface_resistance)
        if (allocated(vegetation_height)) deallocate (vegetation_height)
        if (allocated(leaf_area_index)) deallocate (leaf_area_index)
        if (allocated(albedo)) deallocate (albedo)
        if (allocated(specific_baseflow)) deallocate (specific_baseflow)
        if (allocated(floodplain_infiltration_rate)) deallocate (floodplain_infiltration_rate)
        if (allocated(groundwater_conductivity)) deallocate (groundwater_conductivity)
        if (allocated(subsurface_conductivity)) deallocate (subsurface_conductivity)
        if (allocated(arno_b)) deallocate (arno_b)
        if (allocated(max_soil_water_storage)) deallocate (max_soil_water_storage)
        if (allocated(capillary_threshold_fraction)) deallocate (capillary_threshold_fraction)
        if (allocated(max_capillary_flux)) deallocate (max_capillary_flux)
        if (allocated(brooks_corey_lambda)) deallocate (brooks_corey_lambda)
        if (allocated(surface_routing_coefficient)) deallocate (surface_routing_coefficient)
        if (allocated(groundwater_routing_coefficient)) deallocate (groundwater_routing_coefficient)
        if (allocated(subsurface_routing_coefficient)) deallocate (subsurface_routing_coefficient)
        if (allocated(catchment_order)) deallocate (catchment_order)
        if (allocated(subbasin_outlet_catchment)) deallocate (subbasin_outlet_catchment)
        if (allocated(river_width)) deallocate (river_width)
        if (allocated(downstream_catchment)) deallocate (downstream_catchment)
        if (allocated(longest_reach_length)) deallocate (longest_reach_length)
        if (allocated(longest_reach_slope)) deallocate (longest_reach_slope)
        if (allocated(catchment_subbasin)) deallocate (catchment_subbasin)
        if (allocated(climate_region)) deallocate (climate_region)
        if (allocated(catchment_y)) deallocate (catchment_y)
        if (allocated(catchment_x)) deallocate (catchment_x)
        if (allocated(river_slope)) deallocate (river_slope)
        if (allocated(river_length)) deallocate (river_length)
        if (allocated(drainage_area)) deallocate (drainage_area)
        if (allocated(catchment_area)) deallocate (catchment_area)
        if (allocated(hru_percentage)) deallocate (hru_percentage)
        if (allocated(hru_name)) deallocate (hru_name)
        if (allocated(catchments_per_subbasin)) deallocate (catchments_per_subbasin)
    end subroutine deallocate_parameters

end module parameters
