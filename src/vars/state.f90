module state

    implicit none
    save

    integer :: day, month, year, hour, minute, day_of_year
    real(8) :: julian_day

    real, allocatable :: catchment_q_previous(:), catchment_q_current(:)
    real, allocatable :: capillary_flux(:, :), soil_water_storage(:, :)
    real, allocatable :: groundwater_q(:), subsurface_q(:), surface_q(:)
    real, allocatable :: groundwater_storage(:), subsurface_storage(:), surface_storage(:)
    real, allocatable :: total_water_storage(:), floodplain_infiltration(:)
    real, allocatable :: interception_storage(:, :), evapotranspiration(:, :)
    real, allocatable :: open_water_evaporation_q(:)
    real, allocatable :: potential_open_water_et(:), potential_top_radiation_et(:)
    real, allocatable :: potential_surface_radiation_et(:)

    real, allocatable :: incoming_q_previous(:), outgoing_q_previous(:)
    real, allocatable :: incoming_q_current(:), outgoing_q_current(:)
    real, allocatable :: incoming_groundwater_fraction_current(:)
    real, allocatable :: incoming_subsurface_fraction_current(:)
    real, allocatable :: incoming_surface_fraction_current(:)
    real, allocatable :: outgoing_groundwater_fraction_current(:)
    real, allocatable :: outgoing_subsurface_fraction_current(:)
    real, allocatable :: outgoing_surface_fraction_current(:)
    real, allocatable :: groundwater_routing_volume(:), subsurface_routing_volume(:)
    real, allocatable :: surface_routing_volume(:)
    real, allocatable :: incoming_q_boundary(:, :), outgoing_q_boundary(:, :)
    real, allocatable :: initial_river_q(:, :), flow_velocity(:)
    real, allocatable :: incoming_groundwater_fraction_previous(:)
    real, allocatable :: incoming_subsurface_fraction_previous(:)
    real, allocatable :: incoming_surface_fraction_previous(:)
    real, allocatable :: outgoing_groundwater_fraction_previous(:)
    real, allocatable :: outgoing_subsurface_fraction_previous(:)
    real, allocatable :: outgoing_surface_fraction_previous(:)

    real*8, allocatable :: inertial_q(:), upstream_q(:)
    real*8, allocatable :: current_water_volume(:), previous_water_volume(:)
    real*8, allocatable :: current_flooded_area(:)
    real*8, allocatable :: water_depth(:), water_surface_elevation(:)
    real*8, allocatable :: face_q(:), neighbor_q(:)
    integer, allocatable :: stage_table_index(:)
    real*8, allocatable :: grace_total_water_storage(:)

    real(4), allocatable :: q_river_output(:), water_surface_elevation_output(:)
    real(4), allocatable :: total_water_storage_output(:), flooded_area_output(:), hand_output(:)
    real(4), allocatable :: incremental_q_output(:), et_output(:), groundwater_q_output(:)
    real(4), allocatable :: soil_saturation_output(:)
    real(4), allocatable :: interception_et_output(:), soil_vegetation_et_output(:)
    real(4), allocatable :: open_water_et_output(:), water_hru_et_output(:)
    real(4), allocatable :: potential_open_water_et_output(:)
    real(4), allocatable :: soil_water_output(:), capillary_water_output(:)
    real(4), allocatable :: interception_storage_output(:)
    real(4), allocatable :: surface_storage_depth_output(:), subsurface_storage_depth_output(:)
    real(4), allocatable :: groundwater_storage_depth_output(:)
    real(4), allocatable :: surface_runoff_depth_output(:), subsurface_runoff_depth_output(:)
    real(4), allocatable :: groundwater_runoff_depth_output(:)
    real(4), allocatable :: surface_water_output(:), catchment_q_output(:)

contains

    subroutine allocate_state(catchment_count, hru_count, max_muskingum_reach_count)
        integer, intent(in) :: catchment_count, hru_count
        integer, intent(in) :: max_muskingum_reach_count

        allocate (catchment_q_previous(catchment_count))
        allocate (catchment_q_current(catchment_count))
        allocate (capillary_flux(catchment_count, hru_count))
        allocate (soil_water_storage(catchment_count, hru_count))
        allocate (groundwater_q(catchment_count))
        allocate (subsurface_q(catchment_count))
        allocate (surface_q(catchment_count))
        allocate (groundwater_storage(catchment_count))
        allocate (subsurface_storage(catchment_count))
        allocate (surface_storage(catchment_count))
        allocate (total_water_storage(catchment_count))
        allocate (floodplain_infiltration(catchment_count))
        allocate (interception_storage(catchment_count, hru_count))
        allocate (evapotranspiration(catchment_count, hru_count))
        allocate (open_water_evaporation_q(catchment_count))
        allocate (potential_open_water_et(catchment_count))
        allocate (potential_top_radiation_et(catchment_count))
        allocate (potential_surface_radiation_et(catchment_count))

        allocate (initial_river_q(catchment_count, &
            & max_muskingum_reach_count + 1))
        allocate (incoming_q_boundary(catchment_count + 1, 25))
        allocate (outgoing_q_boundary(catchment_count + 1, 25))
        allocate (incoming_q_previous(catchment_count + 1))
        allocate (outgoing_q_previous(catchment_count))
        allocate (incoming_q_current(catchment_count + 1))
        allocate (outgoing_q_current(catchment_count))
        allocate (incoming_groundwater_fraction_current(catchment_count + 1))
        allocate (incoming_subsurface_fraction_current(catchment_count + 1))
        allocate (incoming_surface_fraction_current(catchment_count + 1))
        allocate (outgoing_groundwater_fraction_current(catchment_count + 1))
        allocate (outgoing_subsurface_fraction_current(catchment_count + 1))
        allocate (outgoing_surface_fraction_current(catchment_count + 1))
        allocate (groundwater_routing_volume(catchment_count))
        allocate (subsurface_routing_volume(catchment_count))
        allocate (surface_routing_volume(catchment_count))
        allocate (flow_velocity(catchment_count))
        allocate (incoming_groundwater_fraction_previous(catchment_count + 1))
        allocate (incoming_subsurface_fraction_previous(catchment_count + 1))
        allocate (incoming_surface_fraction_previous(catchment_count + 1))
        allocate (outgoing_groundwater_fraction_previous(catchment_count))
        allocate (outgoing_subsurface_fraction_previous(catchment_count))
        allocate (outgoing_surface_fraction_previous(catchment_count))

        allocate (inertial_q(catchment_count))
        allocate (upstream_q(3))
        allocate (current_water_volume(catchment_count))
        allocate (previous_water_volume(catchment_count))
        allocate (current_flooded_area(catchment_count))
        allocate (water_depth(catchment_count))
        allocate (water_surface_elevation(catchment_count))
        allocate (face_q(catchment_count))
        allocate (neighbor_q(catchment_count))
        allocate (stage_table_index(catchment_count))
        allocate (grace_total_water_storage(catchment_count))

        allocate (q_river_output(catchment_count))
        allocate (water_surface_elevation_output(catchment_count))
        allocate (flooded_area_output(catchment_count))
        allocate (total_water_storage_output(catchment_count))
        allocate (hand_output(catchment_count))
        allocate (incremental_q_output(catchment_count))
        allocate (et_output(catchment_count))
        allocate (interception_et_output(catchment_count))
        allocate (water_hru_et_output(catchment_count))
        allocate (soil_vegetation_et_output(catchment_count))
        allocate (open_water_et_output(catchment_count))
        allocate (potential_open_water_et_output(catchment_count))
        allocate (soil_water_output(catchment_count))
        allocate (interception_storage_output(catchment_count))
        allocate (capillary_water_output(catchment_count))
        allocate (groundwater_storage_depth_output(catchment_count))
        allocate (surface_storage_depth_output(catchment_count))
        allocate (subsurface_storage_depth_output(catchment_count))
        allocate (groundwater_runoff_depth_output(catchment_count))
        allocate (surface_runoff_depth_output(catchment_count))
        allocate (subsurface_runoff_depth_output(catchment_count))
        allocate (catchment_q_output(catchment_count))
        allocate (surface_water_output(catchment_count))
        allocate (groundwater_q_output(catchment_count))
        allocate (soil_saturation_output(catchment_count))
    end subroutine allocate_state

    subroutine deallocate_state
        if (allocated(soil_saturation_output)) deallocate (soil_saturation_output)
        if (allocated(groundwater_q_output)) deallocate (groundwater_q_output)
        if (allocated(surface_water_output)) deallocate (surface_water_output)
        if (allocated(catchment_q_output)) deallocate (catchment_q_output)
        if (allocated(subsurface_runoff_depth_output)) deallocate (subsurface_runoff_depth_output)
        if (allocated(surface_runoff_depth_output)) deallocate (surface_runoff_depth_output)
        if (allocated(groundwater_runoff_depth_output)) deallocate (groundwater_runoff_depth_output)
        if (allocated(subsurface_storage_depth_output)) deallocate (subsurface_storage_depth_output)
        if (allocated(surface_storage_depth_output)) deallocate (surface_storage_depth_output)
        if (allocated(groundwater_storage_depth_output)) &
            & deallocate (groundwater_storage_depth_output)
        if (allocated(capillary_water_output)) deallocate (capillary_water_output)
        if (allocated(interception_storage_output)) deallocate (interception_storage_output)
        if (allocated(soil_water_output)) deallocate (soil_water_output)
        if (allocated(potential_open_water_et_output)) deallocate (potential_open_water_et_output)
        if (allocated(open_water_et_output)) deallocate (open_water_et_output)
        if (allocated(soil_vegetation_et_output)) deallocate (soil_vegetation_et_output)
        if (allocated(water_hru_et_output)) deallocate (water_hru_et_output)
        if (allocated(interception_et_output)) deallocate (interception_et_output)
        if (allocated(et_output)) deallocate (et_output)
        if (allocated(incremental_q_output)) deallocate (incremental_q_output)
        if (allocated(hand_output)) deallocate (hand_output)
        if (allocated(total_water_storage_output)) deallocate (total_water_storage_output)
        if (allocated(flooded_area_output)) deallocate (flooded_area_output)
        if (allocated(water_surface_elevation_output)) deallocate (water_surface_elevation_output)
        if (allocated(q_river_output)) deallocate (q_river_output)
        if (allocated(grace_total_water_storage)) deallocate (grace_total_water_storage)
        if (allocated(stage_table_index)) deallocate (stage_table_index)
        if (allocated(neighbor_q)) deallocate (neighbor_q)
        if (allocated(face_q)) deallocate (face_q)
        if (allocated(water_surface_elevation)) deallocate (water_surface_elevation)
        if (allocated(water_depth)) deallocate (water_depth)
        if (allocated(current_flooded_area)) deallocate (current_flooded_area)
        if (allocated(previous_water_volume)) deallocate (previous_water_volume)
        if (allocated(current_water_volume)) deallocate (current_water_volume)
        if (allocated(upstream_q)) deallocate (upstream_q)
        if (allocated(inertial_q)) deallocate (inertial_q)
        if (allocated(outgoing_surface_fraction_previous)) &
            & deallocate (outgoing_surface_fraction_previous)
        if (allocated(outgoing_subsurface_fraction_previous)) &
            & deallocate (outgoing_subsurface_fraction_previous)
        if (allocated(outgoing_groundwater_fraction_previous)) &
            & deallocate (outgoing_groundwater_fraction_previous)
        if (allocated(incoming_surface_fraction_previous)) &
            & deallocate (incoming_surface_fraction_previous)
        if (allocated(incoming_subsurface_fraction_previous)) &
            & deallocate (incoming_subsurface_fraction_previous)
        if (allocated(incoming_groundwater_fraction_previous)) &
            & deallocate (incoming_groundwater_fraction_previous)
        if (allocated(flow_velocity)) deallocate (flow_velocity)
        if (allocated(surface_routing_volume)) deallocate (surface_routing_volume)
        if (allocated(subsurface_routing_volume)) deallocate (subsurface_routing_volume)
        if (allocated(groundwater_routing_volume)) deallocate (groundwater_routing_volume)
        if (allocated(outgoing_surface_fraction_current)) &
            & deallocate (outgoing_surface_fraction_current)
        if (allocated(outgoing_subsurface_fraction_current)) &
            & deallocate (outgoing_subsurface_fraction_current)
        if (allocated(outgoing_groundwater_fraction_current)) &
            & deallocate (outgoing_groundwater_fraction_current)
        if (allocated(incoming_surface_fraction_current)) &
            & deallocate (incoming_surface_fraction_current)
        if (allocated(incoming_subsurface_fraction_current)) &
            & deallocate (incoming_subsurface_fraction_current)
        if (allocated(incoming_groundwater_fraction_current)) &
            & deallocate (incoming_groundwater_fraction_current)
        if (allocated(outgoing_q_current)) deallocate (outgoing_q_current)
        if (allocated(incoming_q_current)) deallocate (incoming_q_current)
        if (allocated(outgoing_q_previous)) deallocate (outgoing_q_previous)
        if (allocated(incoming_q_previous)) deallocate (incoming_q_previous)
        if (allocated(outgoing_q_boundary)) deallocate (outgoing_q_boundary)
        if (allocated(incoming_q_boundary)) deallocate (incoming_q_boundary)
        if (allocated(initial_river_q)) deallocate (initial_river_q)
        if (allocated(potential_surface_radiation_et)) deallocate (potential_surface_radiation_et)
        if (allocated(potential_top_radiation_et)) deallocate (potential_top_radiation_et)
        if (allocated(potential_open_water_et)) deallocate (potential_open_water_et)
        if (allocated(evapotranspiration)) deallocate (evapotranspiration)
        if (allocated(interception_storage)) deallocate (interception_storage)
        if (allocated(open_water_evaporation_q)) deallocate (open_water_evaporation_q)
        if (allocated(floodplain_infiltration)) deallocate (floodplain_infiltration)
        if (allocated(total_water_storage)) deallocate (total_water_storage)
        if (allocated(surface_storage)) deallocate (surface_storage)
        if (allocated(subsurface_storage)) deallocate (subsurface_storage)
        if (allocated(groundwater_storage)) deallocate (groundwater_storage)
        if (allocated(surface_q)) deallocate (surface_q)
        if (allocated(subsurface_q)) deallocate (subsurface_q)
        if (allocated(groundwater_q)) deallocate (groundwater_q)
        if (allocated(soil_water_storage)) deallocate (soil_water_storage)
        if (allocated(capillary_flux)) deallocate (capillary_flux)
        if (allocated(catchment_q_current)) deallocate (catchment_q_current)
        if (allocated(catchment_q_previous)) deallocate (catchment_q_previous)
    end subroutine deallocate_state

end module state
